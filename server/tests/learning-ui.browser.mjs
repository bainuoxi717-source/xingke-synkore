// Local smoke check: all AI POSTs are intercepted; fixture notes never touch the database.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 849, height: 1004 } });
  const page = await context.newPage();
  const errors = [];
  const aiPosts = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.route('**/api/**', async (route) => {
    const request = route.request();
    if (/\/learning-feed\/posts\/[^/]+\/signals$/.test(new URL(request.url()).pathname)) return route.fulfill({ json: { ok: true } });
    if (request.method() === 'POST' && /qa\/lecture|restyle|distill/.test(request.url())) { aiPosts.push(request.url()); return route.abort(); }
    return route.continue();
  });
  await page.goto('http://localhost:3930', { waitUntil: 'networkidle' });
  assert.equal(await page.locator('#hero-title').innerText(), 'built for your learning');
  assert.equal(await page.locator('#agent-prompt,#learning-feed').count(), 0);
  await page.getByRole('button', { name: '个性化助手', exact: true }).focus(); await page.keyboard.press('Enter');
  await page.getByRole('button', { name: '添加文件', exact: true }).click();
  assert.equal(await page.getByRole('tab').count(), 3);
  const chooserPromise = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: '选择本地文件', exact: true }).click();
  const chooser = await chooserPromise;
  assert.equal(chooser.isMultiple(), true);
  await chooser.setFiles([]);
  await page.getByRole('button', { name: '添加文件', exact: true }).click();
  await page.getByRole('tab', { name: '课件', exact: true }).click();
  await page.locator('.source-row').first().waitFor();
  assert.ok(await page.locator('.source-row').count() > 0);
  await page.getByRole('tab', { name: '课程笔记', exact: true }).click();
  await page.locator('.source-row').first().waitFor();
  await page.getByRole('button', { name: '整理笔记', exact: true }).first().click();
  await page.locator('.source-plan').waitFor();
  assert.match(await page.locator('.source-plan').innerText(), /模型请求/);
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.screenshot({ path: `${root}/docs/learning-sources-desktop.png` });
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  const catalog = await (await context.request.get('http://localhost:3930/api/learning-sources')).json();
  const lesson = catalog.notes.items.find((item) => item.status === 'pending');
  const id = `lecture-note:${lesson.courId}`;
  const attachment = { id, kind: 'lecture-note', name: `浏览器测试课程 · 第${lesson.leti}节`, courseName: '浏览器测试课程', leti: lesson.leti, courId: lesson.courId, teacher: lesson.teacher, content_type: 'text/markdown', size: 0, url: `/api/learning-sources/${encodeURIComponent(id)}/file` };
  await page.route('**/api/learning-sources', (route) => route.fulfill({ json: { ...catalog, notes: { ...catalog.notes, items: [{ ...lesson, hasNotes: true, status: 'ready', statusLabel: '已整理' }] } } }));
  await page.route(`**/api/learning-sources/${encodeURIComponent(id)}`, (route) => route.fulfill({ json: { ok: true, attachment, markdown: '# 测试课程笔记\n\n这是测试夹具，验证预览和选中传递。' } }));
  await page.getByRole('button', { name: '添加文件', exact: true }).click();
  await page.getByRole('tab', { name: '课程笔记', exact: true }).click();
  await page.getByRole('button', { name: '预览', exact: true }).click();
  await page.getByRole('button', { name: '添加到问题', exact: true }).click();
  await page.getByRole('button', { name: '已添加', exact: true }).waitFor();
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await page.getByRole('combobox', { name: '选择讲解人物' }).selectOption('skill:feynman');
  await page.getByRole('textbox', { name: '课堂问题' }).fill('帮我解释这节课的核心概念');
  await page.getByRole('textbox', { name: '课堂问题' }).waitFor();
  await page.waitForFunction(() => document.querySelector('input[aria-label="课堂问题"]')?.value === '帮我解释这节课的核心概念');
  assert.equal(await page.getByRole('textbox', { name: '课堂问题' }).inputValue(), '帮我解释这节课的核心概念');
  assert.equal(await page.getByRole('combobox', { name: '选择讲解人物' }).inputValue(), 'skill:feynman');
  await page.locator('.attachment-ready').waitFor();
  assert.match(await page.locator('.attachment-ready').innerText(), /浏览器测试课程/);
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('.attachment-ready').waitFor();
  const submitted = [];
  await page.route('**/api/qa/call-plan', (route) => route.fulfill({ json: { ok: true, configured: false, calls: 1 } }));
  await page.route('**/api/qa/lecture/stream', (route) => {
    submitted.push(route.request().postDataJSON());
    const body = submitted.length === 1 ? 'event: delta\ndata: {"text":"测试讲解"}\n\nevent: done\ndata: {"ok":true,"sessionId":0,"full":"测试讲解","coverage":"partial"}\n\n' : 'event: error\ndata: {"message":"测试错误不能消失"}\n\n';
    return route.fulfill({ contentType: 'text/event-stream', body });
  });
  await page.getByRole('textbox', { name: '课堂问题' }).fill('先讲概念');
  await page.getByRole('button', { name: '发送课堂问题' }).click();
  await page.getByText('测试讲解', { exact: true }).waitFor();
  assert.equal(await page.locator('.attachment-ready').count(), 1);
  await page.getByRole('textbox', { name: '课堂问题' }).fill('再讲具体点');
  await page.getByRole('button', { name: '发送课堂问题' }).click();
  await page.getByText('⚠️ 测试错误不能消失', { exact: true }).waitFor();
  assert.deepEqual(submitted[0].attachmentIds, submitted[1].attachmentIds);
  assert.deepEqual(submitted[0].attachmentIds, [id]);
  assert.equal(submitted[1].personaId, 'skill:feynman');
  await page.getByRole('button', { name: '换个讲法', exact: true }).click();
  await page.getByRole('combobox', { name: '选择讲解人物' }).waitFor();
  await page.waitForTimeout(250);
  assert.equal(await page.getByRole('combobox', { name: '选择讲解人物' }).inputValue(), 'skill:feynman');
  assert.match(await page.locator('.ln-main').innerText(), new RegExp(`第${lesson.leti}节`));
  assert.equal(aiPosts.length, 0, 'selection and navigation must not generate');
  assert.deepEqual(errors, []);
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await mobile.goto('http://localhost:3930', { waitUntil: 'networkidle' });
  await mobile.getByRole('button', { name: '个性化助手', exact: true }).focus(); await mobile.keyboard.press('Enter');
  await mobile.getByRole('button', { name: '添加文件', exact: true }).click();
  await mobile.getByRole('tab', { name: '课程笔记', exact: true }).click();
  await mobile.locator('.source-row').first().waitFor();
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const box = await mobile.getByRole('dialog').boundingBox();
  assert.ok(box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 844);
  await mobile.screenshot({ path: `${root}/docs/learning-sources-mobile.png` });
  console.log(JSON.stringify({ passed: true, desktop: '849x1004', mobile: '390x844', materials: catalog.materials.length, lectures: catalog.notes.total, aiCalls: aiPosts.length, mockedAnswers: submitted.length, pageErrors: errors }));
} finally { await browser.close(); }
