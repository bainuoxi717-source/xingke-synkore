import express from 'express';
import path from 'node:path';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const root = path.resolve(process.argv[2]);
const app = express(); app.use(express.static(path.join(root, 'dist'), { acceptRanges: false })); app.get('*', (req, res) => res.sendFile(path.join(root, 'dist/index.html')));
const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = [], failed = [], apiNetwork = [];
try {
  const page = await browser.newPage({ viewport: { width: 1366, height: 1000 } });
  page.setDefaultTimeout(15000);
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) failed.push({ url: r.url(), status: r.status() }); });
  page.on('request', r => { if (/\/api\/|127\.0\.0\.1:8771/.test(r.url())) apiNetwork.push(r.url()); });
  await page.goto(base, { waitUntil: 'networkidle' }); await page.getByText('公开演示 · 预设内容').waitFor();
  await fs.mkdir(path.join(root, 'evidence'), { recursive: true });
  await page.screenshot({ path: path.join(root, 'evidence/home.png'), fullPage: true });
  await page.goto(base + '/qa', { waitUntil: 'networkidle' });
  await page.getByLabel('选择课堂课次').selectOption('900002');
  await page.getByLabel('课堂问题', { exact: true }).fill('前测是什么？');
  await page.getByRole('button', { name: '发送课堂问题', exact: true }).click();
  await page.getByText('前测是在引入实验刺激之前', { exact: false }).first().waitFor();
  await page.getByRole('button', { name: '发送课堂问题', exact: true }).isEnabled();
  await page.getByRole('button', { name: '换个讲法', exact: true }).click();
  await page.waitForURL('**/restyle?**');
  await page.getByText('换一个直观讲法', { exact: false }).first().waitFor();
  await page.goto(base + '/learning-feed', { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.feed-card').count(), 4);
  await page.locator('.feed-card-cover').first().click();
  const dialog = page.getByRole('dialog'); await dialog.waitFor();
  await dialog.getByText('公开示例：内容与讨论已预先编写', { exact: false }).waitFor();
  await dialog.getByLabel('轮到你了').fill('我认为还需要比较条件。');
  await dialog.getByRole('button', { name: '发布并继续思考', exact: true }).click();
  await dialog.getByText('我认为还需要比较条件。', { exact: true }).waitFor();
  await page.goto(base + '/replay-demo', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelector('video')?.duration === 300, null, { timeout: 15000 });
  await page.getByRole('button', { name: '回答提问', exact: true }).click();
  await page.locator('[data-cue="pretest"]').waitFor();
  await page.waitForFunction(() => { const e = document.querySelector('.replay-device-preview > img'); return e?.complete && e.naturalWidth > 0; }, null, { timeout: 15000 });
  await page.screenshot({ path: path.join(root, 'evidence/replay.png'), fullPage: true });
  const mark = page.getByRole('button', { name: /标记重点|是重点/ }).first();
  if (await mark.count()) { await mark.click(); await page.getByRole('status').filter({ hasText: '已标记' }).waitFor(); }
  await page.reload({ waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelector('video')?.duration === 300, null, { timeout: 15000 });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(root, 'evidence/mobile.png'), fullPage: true });
  await page.goto(base + '/settings', { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: '公开演示说明' }).waitFor();
  assert.equal(await page.locator('input[type=password]').count(), 0);
  assert.deepEqual(errors, []); assert.deepEqual(failed, []); assert.deepEqual(apiNetwork, []);
  console.log('PASS public demo: home, scoped preset QA, restyle, four feed articles, local comment persistence, 300s replay, answer jump, board-card previews, marks, direct-route reload, mobile and no outgoing API/USB requests.');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
